#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { toolGroupLoaders } from "../src/mcp/tools/index.ts";

const outputUrl = new URL("../src/mcp/tool-manifest.generated.ts", import.meta.url);
const entries = [];
const names = new Set();

for (const [groupId, load] of Object.entries(toolGroupLoaders)) {
  const modules = await load();
  for (const tool of modules) {
    const name = tool.definition.name;
    if (names.has(name)) throw new Error(`Duplicate MCP tool registration while generating manifest: ${name}`);
    names.add(name);
    entries.push({ groupId, definition: tool.definition, enabledByDefault: tool.enabledByDefault });
  }
}

const source = `/* This file is generated by scripts/generate-tool-manifest.mjs. Do not edit by hand. */\nimport type { ToolManifestEntry } from "./manifest-types.js";\n\nexport const toolManifest: readonly ToolManifestEntry[] = ${JSON.stringify(entries, null, 2)};\n`;
const check = process.argv.includes("--check");

if (check) {
  const current = await readFile(outputUrl, "utf8").catch(() => "");
  if (current !== source) {
    console.error(`Tool manifest is stale. Run: npm run generate:tool-manifest\nExpected ${entries.length} tools in ${fileURLToPath(outputUrl)}.`);
    process.exit(1);
  }
  console.log(`Tool manifest is current (${entries.length} tools).`);
} else {
  await writeFile(outputUrl, source, "utf8");
  console.log(`Generated ${entries.length} tool definitions at ${fileURLToPath(outputUrl)}.`);
}
